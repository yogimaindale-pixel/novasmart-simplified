# Import 'json' module: Used for encoding Python dictionaries into JSON formatted strings for API output.
import json

# Import 'sqlite3' module: Provides a lightweight SQL database engine that runs in memory without setup.
import sqlite3

# Import 'typing' annotations: Helps developers understand expected data types for parameters and return values.
from typing import Dict, Any, List, Tuple


# ------------------------------------------------------------------------------
# SECTION 2: DATABASE INITIALIZATION AND SAMPLE DATA CREATION
# ------------------------------------------------------------------------------

def initialize_demo_database() -> sqlite3.Connection:
    """
    Creates an in-memory SQLite database and populates it with sample product data.
    
    Returns:
        sqlite3.Connection: Active database connection object.
    """
    # Step 1: Open an in-memory database connection (":memory:" lives strictly in RAM).
    db_connection = sqlite3.connect(":memory:")
    
    # Step 2: Create a database cursor object (the cursor is used to execute SQL queries).
    db_cursor = db_connection.cursor()
    
    # Step 3: Define the SQL command to create the 'products' table.
    create_table_sql = """
        CREATE TABLE products (
            product_id TEXT PRIMARY KEY,
            name TEXT NOT NULL,
            category TEXT NOT NULL,
            price REAL NOT NULL,
            stock_count INTEGER NOT NULL
        )
    """
    # Step 4: Run the table creation SQL statement on the database.
    db_cursor.execute(create_table_sql)
    
    # Step 5: Define a list of tuples containing sample retail product records.
    sample_products = [
        ("P101", "NovaSmart Wireless Earbuds", "Electronics", 49.99, 150),
        ("P102", "NovaSmart Ergonomic Mouse", "Electronics", 29.99, 85),
        ("P103", "NovaSmart USB-C Hub", "Accessories", 19.99, 200)
    ]
    
    # Step 6: Define parameterized SQL query for safe record insertion.
    insert_sql = "INSERT INTO products VALUES (?, ?, ?, ?, ?)"
    
    # Step 7: Execute batch insertion of sample product records into the database table.
    db_cursor.executemany(insert_sql, sample_products)
    
    # Step 8: Commit (save) all database transactions so they are permanently written to memory.
    db_connection.commit()
    
    # Step 9: Return the fully prepared database connection object.
    return db_connection


# ------------------------------------------------------------------------------
# SECTION 3: MODEL CONTEXT PROTOCOL (MCP) TOOL INTEGRATION
# ------------------------------------------------------------------------------

def query_retail_database(query_sql: str, db_connection: sqlite3.Connection) -> List[Dict[str, Any]]:
    """
    Executes a read-only SQL query against the retail database.
    This simulates how an AI agent uses Model Context Protocol (MCP) tools to query data.

    Args:
        query_sql (str): SQL query string generated by or passed to the tool.
        db_connection (sqlite3.Connection): Database connection to execute against.

    Returns:
        List[Dict[str, Any]]: List of dictionary objects, where each key matches a table column.
    """
    # Step 1: Obtain a cursor object from the provided database connection.
    cursor = db_connection.cursor()
    
    # Step 2: Execute the SQL statement passed in the arguments.
    cursor.execute(query_sql)
    
    # Step 3: Extract column header names from the cursor description metadata.
    column_names = [col_description[0] for col_description in cursor.description]
    
    # Step 4: Retrieve all matching rows returned by the query.
    raw_rows = cursor.fetchall()
    
    # Step 5: Convert raw tuple rows into dictionary key-value pairs (column_name: cell_value).
    structured_results = []
    for row in raw_rows:
        # Zip combines the column names list with the row values tuple into pairs.
        row_dict = dict(zip(column_names, row))
        # Append the dictionary row to our result list.
        structured_results.append(row_dict)
        
    # Step 6: Return the clean, structured list of product records.
    return structured_results


