# SECTION 4: AGENT DEFINITION AND TOOL ROUTING CLASS
# ------------------------------------------------------------------------------

class NovaSmartAgent:
    """
    Represents an AI Agent workload capable of understanding prompts,
    executing tools, and returning audited responses.
    """
    
    def __init__(self, agent_name: str, system_instruction: str, db_connection: sqlite3.Connection):
        """
        Initializes the agent instance with an identity, persona, and database tool binding.
        """
        # Property 1: Store the human-readable identifier for the agent.
        self.agent_name = agent_name
        
        # Property 2: Store the system prompt defining the agent's behavior and constraints.
        self.system_instruction = system_instruction
        
        # Property 3: Store the database connection for tool execution.
        self.db_connection = db_connection

    def execute_tool(self, tool_name: str, tool_arguments: Dict[str, Any]) -> Any:
        """
        Dispatches tool execution requests to the appropriate tool function.
        """
        # Check if the tool requested is the database query tool.
        if tool_name == "query_retail_database":
            # Extract the SQL query parameter safely from the dictionary.
            sql = tool_arguments.get("sql", "SELECT * FROM products")
            # Call the database query function and return results.
            return query_retail_database(sql, self.db_connection)
        else:
            # Raise an error if an unauthorized or unknown tool is invoked.
            raise ValueError(f"Unknown tool requested: '{tool_name}'")

    def process_user_prompt(self, prompt_text: str) -> Dict[str, Any]:
        """
        Processes an incoming user request, determines tool requirements, and generates output.
        """
        # Step 1: Print a log line indicating the prompt received.
        print(f"[{self.agent_name}] Processing user prompt: '{prompt_text}'")
        
        # Step 2: Determine if database lookup tool execution is required based on prompt content.
        requires_product_lookup = "product" in prompt_text.lower() or "price" in prompt_text.lower()
        
        if requires_product_lookup:
            # Construct read-only SQL query string for product retrieval.
            target_sql = "SELECT product_id, name, price, stock_count FROM products"
            
            # Execute the tool via the internal router.
            data_output = self.execute_tool("query_retail_database", {"sql": target_sql})
            
            # Construct structured audit response dictionary.
            return {
                "agent_name": self.agent_name,
                "status": "SUCCESS",
                "message": f"Retrieved {len(data_output)} products from database.",
                "data": data_output
            }
        else:
            # Construct response dictionary when no tool calls are needed.
            return {
                "agent_name": self.agent_name,
                "status": "SUCCESS",
                "message": "Prompt processed successfully without tool invocation.",
                "data": []
            }


